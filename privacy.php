<p><strong>COPPA (Children Online Privacy Protection Act)</strong></p>
<p>
Non rivolgiamo attività di marketing specifiche a minori di 13 anni. Molti studenti usano questo sito tramite
scuole e sistemi di gestione dell'apprendimento; docenti e istituti sono responsabili dell'uso appropriato
con i propri studenti.
</p>
<p><strong>Conservazione dei dati</strong></p>
<p>
Eliminiamo periodicamente i dati inattivi secondo una pianificazione regolare. Quando i dati scadono o vengono rimossi manualmente,
questo servizio non ne conserva copie di backup. Mantenendo nel sistema solo i dati attivi,
riduciamo la quantità complessiva di informazioni personali memorizzate in ogni momento.
Se non effettui l'accesso per un lungo periodo, i tuoi dati personali su questo server potrebbero essere
cancellati senza ulteriori azioni da parte tua.
</p>
<p><strong>Analisi dei dati</strong></p>
<p>
Limitiamo l'analisi dei dati personali ai report richiesti da un ente o necessari per la contabilità,
il supporto tecnico e le statistiche generali di sistema. Possiamo svolgere analisi interne
per migliorare affidabilità, funzionalità o prestazioni. In particolare, <strong>non</strong> useremo
tecniche di machine learning o intelligenza artificiale per profilare o analizzare il comportamento
di studenti e docenti che usano il nostro sito.
</p>
<p><strong>Filosofia generale</strong></p>
<p>
Si dice spesso che se non paghi per un servizio, allora il prodotto sei tu. Per questo servizio
tu non sei il prodotto, e non lo sono nemmeno i tuoi dati o le tue attività. Conserviamo solo i dati
strettamente necessari a supportare i tuoi obiettivi di insegnamento e apprendimento, e per nessun altro scopo.
Ovunque sia possibile, ti diamo il controllo sulla conservazione dei tuoi dati e rispettiamo le tue scelte.
</p>
<p>
Il nostro obiettivo è rispettare la lettera e lo spirito delle norme sulla privacy, come il Family
Educational Rights and Privacy Act (FERPA) e il Regolamento generale sulla protezione dei dati dell'UE
(GDPR). Puntiamo a un impegno verso la privacy degli studenti che vada oltre i requisiti minimi di legge.
</p>
<p>
Gran parte del software usato per gestire questo servizio è open source, quindi puoi esaminare e verificare
cosa facciamo in materia di privacy e, se vuoi, aiutarci a migliorare il nostro approccio a questo tema importante.
</p>
