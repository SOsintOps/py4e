        <h2>Informativa sulla privacy</h2>
<p>
Questa informativa descrive come <em>Python per tutti</em> (PY4E) raccoglie, usa e protegge i dati
personali quando usi il nostro sito di insegnamento e apprendimento,
<a href="https://www.py4e.com/">www.py4e.com</a>.
PY4E fornisce materiali didattici aperti, attività con correzione automatica e strumenti correlati per studenti
e docenti. Ti invitiamo a leggere questa informativa per capire come gestiamo le tue informazioni.
</p>
<p><strong>Quali dati personali raccogliamo?</strong></p>
<p>
Quando crei un account, effettui l'accesso o avvii attività da un sistema di gestione dell'apprendimento (LMS),
possiamo raccogliere informazioni come il tuo nome, l'indirizzo email, gli identificativi del corso o del contesto,
i voti, gli esercizi consegnati, i messaggi nei forum di discussione, i dettagli del profilo e altri dati analoghi necessari
al funzionamento del sito.
</p>
<p><strong>Quando raccogliamo le informazioni?</strong></p>
<p>
Raccogliamo informazioni quando ti registri o effettui l'accesso, avvii strumenti da un LMS, completi
esercizi con correzione automatica, partecipi alle discussioni, aggiorni il tuo profilo o usi
funzionalità che richiedono un account o il salvataggio dei tuoi progressi.
</p>
<p><strong>Come proteggiamo le tue informazioni?</strong></p>
<p>
I tuoi dati personali sono memorizzati su sistemi protetti e accessibili solo a un numero limitato
di persone che hanno bisogno di accedervi per gestire e supportare il servizio e che sono tenute a
mantenerli riservati. Le connessioni al sito usano la crittografia HTTPS (TLS).
</p>
<p><strong>Usiamo i cookie?</strong></p>
<p>
Sì. I cookie sono piccoli file che un sito o il suo fornitore di servizi trasferisce sul tuo dispositivo
attraverso il browser web (se lo consenti), in modo che il sito possa riconoscere il browser e ricordare
alcune informazioni.
</p>
<p><strong>Usiamo i cookie per:</strong></p>
<ul>
<li>Comprendere e salvare le tue preferenze e la tua identità per le visite future.</li>
<li>Raccogliere dati statistici usati esclusivamente per monitorare e migliorare il sito.</li>
</ul>
<p><strong>Se disattivi i cookie nel browser:</strong></p>
<p>
Se disattivi i cookie, non potrai accedere direttamente al sito.
</p>
<p>
<strong>Puoi</strong> comunque usare gli strumenti didattici di questo sistema quando vengono avviati da un LMS con
i cookie disattivati, poiché tali applicazioni didattiche <em>non usano né richiedono cookie</em>
e funzionano regolarmente anche con i cookie disattivati.
</p>
<p><strong>Divulgazione a terzi</strong></p>
<p>
Non vendiamo, scambiamo né trasferiamo in altro modo a soggetti esterni i tuoi dati di identificazione personale
per finalità di marketing.
</p>
<p><strong>Collegamenti e servizi di terze parti</strong></p>
<p>
Le nostre pagine possono contenere collegamenti a siti esterni (ad esempio piattaforme video, corsi partner o repository
open source) oppure integrare servizi opzionali di terze parti descritti qui sotto. Tali siti e servizi
hanno proprie informative sulla privacy, sulle quali non abbiamo alcun controllo.
</p>
<p><strong>Pubblicità</strong></p>
<p>
Non mostriamo pubblicità di terze parti su questo sito.
</p>
